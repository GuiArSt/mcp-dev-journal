#!/usr/bin/env node
/**
 * Generate Postgres DDL from live SQLite journal.db schema.
 *
 * Usage:
 *   node scripts/fortress-sqlite-to-pg.mjs [--out path.sql]
 */

import Database from "better-sqlite3";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..", "..");
const dbPath =
  process.env.JOURNAL_DB_PATH || path.join(root, "data", "journal.db");

const SKIP_TABLES = new Set(["sqlite_sequence"]);

const FORTRESS_COLUMN_PATCHES = {
  media_assets: [
    { from: /data TEXT NOT NULL/i, to: "data TEXT" },
    { append: "object_key TEXT" },
  ],
  entry_attachments: [
    { from: /data BLOB NOT NULL/i, to: "data BYTEA" },
    { from: /data BYTEA NOT NULL/i, to: "data BYTEA" },
    { append: "object_key TEXT" },
  ],
};

function convertSqliteDefaults(pg) {
  return pg.replace(/datetime\('now'\)/gi, "CURRENT_TIMESTAMP");
}

/** Postgres requires referenced tables to exist — defer FKs to a second migration. */
function splitForeignKeys(pg) {
  const alters = [];
  let body = pg;

  // Table-level FOREIGN KEY clauses
  body = body.replace(
    /,\s*FOREIGN KEY\s*\([^)]+\)\s*REFERENCES\s+[^)]+\)(?:\s*ON DELETE\s+\w+)?/gi,
    (match) => {
      alters.push(match.replace(/^,\s*/, "ALTER_PLACEHOLDER"));
      return "";
    },
  );

  // Column-level REFERENCES (keep column, drop reference)
  body = body.replace(
    /\s+REFERENCES\s+([a-zA-Z0-9_"']+)\([^)]+\)(?:\s*ON DELETE\s+\w+)?/gi,
    (match, table) => {
      alters.push(`REFERENCES ${table}`);
      return "";
    },
  );

  // Clean trailing commas before closing paren
  body = body.replace(/,(\s*\))/g, "$1");
  return { ddl: body, fkHints: alters };
}

function convertCreateTable(sql, tableName) {
  let pg = sql
    .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/gi, "BIGSERIAL PRIMARY KEY")
    .replace(/\bAUTOINCREMENT\b/gi, "")
    .replace(/\bBLOB\b/gi, "BYTEA")
    .replace(/\bREAL\b/gi, "DOUBLE PRECISION")
    .replace(/^CREATE TABLE /i, "CREATE TABLE IF NOT EXISTS ");

  const patches = FORTRESS_COLUMN_PATCHES[tableName];
  if (patches) {
    for (const p of patches) {
      if (p.from) pg = pg.replace(p.from, p.to);
      if (p.append) {
        pg = pg.replace(/\)\s*;?\s*$/, `, ${p.append}\n);`);
      }
    }
  }

  pg = convertSqliteDefaults(pg);

  return pg.endsWith(";") ? pg : `${pg};`;
}

function convertCreateTableWithFk(sql, tableName) {
  const ddl = convertCreateTable(sql, tableName);
  return splitForeignKeys(ddl);
}

function convertIndex(sql) {
  return sql
    .replace(/^CREATE INDEX /i, "CREATE INDEX IF NOT EXISTS ")
    .replace(/^CREATE UNIQUE INDEX /i, "CREATE UNIQUE INDEX IF NOT EXISTS ");
}

function main() {
  if (!fs.existsSync(dbPath)) {
    console.error(`Database not found: ${dbPath}`);
    process.exit(1);
  }

  const db = new Database(dbPath, { readonly: true });
  const tables = db
    .prepare(
      `SELECT name, sql FROM sqlite_master
       WHERE type = 'table' AND sql IS NOT NULL
       ORDER BY name`,
    )
    .all();

  const indexes = db
    .prepare(
      `SELECT name, sql FROM sqlite_master
       WHERE type = 'index' AND sql IS NOT NULL
       ORDER BY name`,
    )
    .all();

  db.close();

  const lines = [
    "-- FORTRESS-001: Postgres mirror of Tartarus SQLite vault",
    "-- Generated by web/scripts/fortress-sqlite-to-pg.mjs — do not hand-edit; regenerate instead",
    `-- Source: ${dbPath}`,
    `-- Generated: ${new Date().toISOString()}`,
    "",
    "CREATE TABLE IF NOT EXISTS fortress_sync_meta (",
    "  id BIGSERIAL PRIMARY KEY,",
    "  table_name TEXT NOT NULL UNIQUE,",
    "  sqlite_row_count INTEGER,",
    "  pushed_row_count INTEGER,",
    "  last_pushed_at TIMESTAMPTZ DEFAULT NOW(),",
    "  checksum TEXT",
    ");",
    "",
  ];

  const fkHints = [];

  for (const { name, sql } of tables) {
    if (SKIP_TABLES.has(name)) continue;
    const { ddl, fkHints: hints } = convertCreateTableWithFk(sql, name);
    if (hints.length) fkHints.push(`-- ${name}`, ...hints.map((h) => `-- ${h}`), "");
    lines.push(`-- ${name}`);
    lines.push(ddl);
    lines.push("");
  }

  if (fkHints.length) {
    lines.push("-- Foreign keys omitted in v1 mirror (SQLite order != Postgres-safe order).");
    lines.push("-- Re-add selectively when hosted-lite needs strict referential integrity.");
    lines.push(...fkHints);
  }

  lines.push("-- Indexes");
  for (const { sql } of indexes) {
    if (!sql) continue;
    if (sql.includes("sqlite_autoindex")) continue;
    lines.push(convertIndex(sql) + (sql.endsWith(";") ? "" : ";"));
  }

  const outArg = process.argv.indexOf("--out");
  const outPath =
    outArg >= 0
      ? process.argv[outArg + 1]
      : path.join(root, "docs", "supabase-migrations", "fortress_001_schema.sql");

  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  const body = lines.join("\n");
  fs.writeFileSync(outPath, body, "utf8");
  console.log(`Wrote ${outPath} (${tables.length} tables, ${indexes.length} indexes)`);
}

main();
